"""Compile MACE tensor products with a data-dependent short-range edge count."""
import torch
from torch import Tensor


def _pad_edge_rows(values: Tensor) -> Tensor:
    return torch.cat((values, values.new_zeros((2, values.shape[1]))))


def prepare_edge_tensor_products(core) -> None:
    """Give e3nn's contraction a provably nonsingleton batch of independent edges.

    A short-range cutoff can leave zero or one directed edge. The tensor-product
    code generated by e3nn chooses contraction layouts by testing that dimension
    for equality to one. Append two zero feature/weight rows and remove their
    outputs so Dynamo can prove the internal layout without inspecting positions.
    """
    core._native_empty_short_range_forces = True
    for block in core.blocks:
        kernel = block.interaction.conv_tp._compiled_main_left_right
        graph = kernel.graph
        inputs = [(node, tuple(node.users)) for node in graph.nodes if node.op == "placeholder"]
        first_operation = next(node for node in graph.nodes if node.op != "placeholder")
        with graph.inserting_before(first_operation):
            for edge_input, users in inputs:
                padded = graph.call_function(_pad_edge_rows, (edge_input,))
                for user in users:
                    user.replace_input_with(edge_input, padded)
            count = graph.call_method("size", (inputs[0][0], 0))
        output = next(node for node in graph.nodes if node.op == "output")
        with graph.inserting_before(output):
            real_edges = graph.call_method("narrow", (output.args[0], 0, 0, count))
        output.args = (real_edges,)
        graph.lint()
        kernel.recompile()
